package сode_reading.JavaCodeReading;

public class A45 {
    public static void main(String[] args) {
        int value = 2;

        switch (value) {
            case 1:
                System.out.println("A");
            case 2:
                System.out.println("B");
            case 3:
                System.out.println("C");
            default:
                System.out.println("D");
        }
    }
}
