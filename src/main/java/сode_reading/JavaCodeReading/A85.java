package сode_reading.JavaCodeReading;

public class A85 {
    public static void main(String[] args) {
        int day = 2;

        switch (day) {
            case 1:
                System.out.println("Monday");
            case 2:
                System.out.println("Tuesday");
            case 3:
                System.out.println("Wednesday");
                break;
            default:
                System.out.println("Unknown");
        }
    }
}
